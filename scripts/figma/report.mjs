// Writes figma/REPORT.md: the state of the Figma library in one page, from the recorded
// checks (figma/reports/parity.json and lint.json) and figma/components.json.
//
//   npm run figma:report
import { readFile, writeFile } from 'node:fs/promises'

const data = JSON.parse(await readFile('figma/components.json', 'utf8'))
const parity = JSON.parse(await readFile('figma/reports/parity.json', 'utf8'))
const lint = JSON.parse(await readFile('figma/reports/lint.json', 'utf8'))
const byName = (list, key) => Object.fromEntries(list.map((x) => [x[key], x]))
const p = byName(parity.sets, 'name'), l = byName(lint.pages, 'page')

const rows = data.components.map((c) => {
  const r = p[c.name], q = l[c.page]
  if (!r || !q) throw new Error(`${c.name}: no recorded ${!r ? 'parity' : 'lint'} result`)
  const notes = [q.disabledExempt ? `${q.disabledExempt} disabled text (exempt)` : '', q.overBackdropPasses ? `${q.overBackdropPasses} on a backdrop (pass)` : ''].filter(Boolean).join('; ')
  const clean = !q.hardCoded && !q.defaultNames && !q.contrastFailures
  return `| ${c.name} | ${c.variants.length} | ${r.matched}/${r.checked}${r.strict != null && r.strict !== r.matched ? ` (${r.strict} strict)` : ''} | ${clean ? 'clean' : `${q.hardCoded} colours, ${q.defaultNames} names, ${q.contrastFailures} contrast`}${notes ? ` (${notes})` : ''} | #${r.pr} |`
})
const total = parity.sets.reduce((t, s) => ({ checked: t.checked + s.checked, matched: t.matched + s.matched }), { checked: 0, matched: 0 })
const rb = parity.readBack
const md = `# Figma library report

*Generated by \`npm run figma:report\` from \`figma/reports/\` (checks run ${parity.date}). Prototype · AcmeCo is a fictional brand.*

**File:** \`acmeco-ds library (prototype, not affiliated with AcmeCo)\`, key \`QWDrlOIdTF69URf4yNO1QR\`, in Drafts.

## Summary

- **${rb.sets} component sets, ${rb.variants} variants**, each read back from Figma and equal to the code's variant list; every set has its description, a documentation panel and the prototype label.
- **Parity with the rendered code: ${total.matched} of ${total.checked} fields match** (colours, borders, radii, sizes, padding, gaps, type, focus rings, icons, positions).
- **Lint: 0 hard-coded colours, 0 default layer names, 0 text contrast failures** on all ${lint.pages.length} pages (Icons included). Disabled text is listed apart, as WCAG exempts it.
- **Variables:** Primitives ${rb.variables.Primitives}, Semantic ${rb.variables.Semantic}, Component ${rb.variables.Component}; ${rb.textStyles} text styles, ${rb.effectStyles} effect styles; ${rb.icons} icons. Digests match the repo (\`figma/sync-log.md\`).

## Per component

| Set | Variants | Parity | Lint | PR |
|---|---|---|---|---|
${rows.join('\n')}

## How the checks work

- **Parity** compares each Figma variant, field by field, with the computed styles of the same component rendered in Storybook (\`scripts/figma/parity-code.mjs\` → \`figma/parity/<id>-code.json\`; \`scripts/figma/figma-parity.js\` in Figma). Widths and positions that follow text may differ by up to 1px because Figma measures text a fraction wider than the browser; "strict" counts matches within half a pixel. Each set is checked when it is built or changed (the PR column); the phase 5 sets' code styles haven't changed since their checks.
- **Lint** (\`scripts/figma/figma-lint.js\`) walks every generated layer: any visible fill or stroke not bound to a variable, any layer still called Frame or Rectangle, and text contrast against the nearest fill (every stop of a gradient).
- **Re-running everything:** \`node scripts/figma/render-components.mjs report\` writes the parity checks for every set in two scripts and one lint script for every page; run them with the Figma MCP's \`use_figma\` and record the results in \`figma/reports/\`.

## Known limits

${(rb.knownMismatches ?? []).map((m) => `- Known mismatch: ${m}.\n`).join('')}- The Text field set has no multiline variant; the contact form's message box is drawn with the field tokens.
- Motion (the assistant's moving edge, thinking dots, transitions) is shown as stills (decision 33); the timings are on the "Motion and Fluid Layout tokens" page.
- Phone layouts are shown where a component changes shape (the property card's narrow width, broker identity's narrow row); the dialogs' full-screen phone layout is in Storybook.
- Code Connect isn't available on the Pro plan; \`figma/components.json\` maps every set to its code path and props instead.
`
await writeFile('figma/REPORT.md', md)
console.log(`✔ figma/REPORT.md: ${rows.length} sets, parity ${total.matched}/${total.checked}`)
