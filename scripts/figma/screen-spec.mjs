// Turns a rendered screen into a Figma screen spec (phase 6d, decisions 34 and 46).
//
//   node scripts/figma/screen-spec.mjs <screen id>     (Storybook must be running)
//
// Reads the story named in scripts/figma/screens/<id>.mjs with Playwright at its window size
// and writes figma/screens/<id>.json: every element a component marked (src/components/ds.ts)
// as a library instance with its box, variant and text; marked backgrounds (bands, the list
// column, dividers) as filled rectangles; marked text (Heading, Text) in its type style; and
// the boxes of the notes' targets. scripts/figma/figma-screen.js builds it in Figma.
import { writeFile, mkdir } from 'node:fs/promises'
import { chromium } from 'playwright'

const id = process.argv[2]
const { screen } = await import(`./screens/${id}.mjs`)
const { width, height } = screen.viewport

function read({ notes, links, width, height }) {
  const r2 = (x) => Math.round(x * 100) / 100
  const boxOf = (el) => { const b = el.getBoundingClientRect(); return { x: r2(b.x), y: r2(b.y), w: r2(b.width), h: r2(b.height) } }
  const visible = (el) => {
    const b = el.getBoundingClientRect()
    return el.getClientRects().length && b.width > 1 && b.height > 0 && b.right > 0 && b.bottom > 0 && b.left < width && b.top < height
  }
  const insideInstance = (el) => !!el.parentElement?.closest('[data-ds]')
  const frames = [...document.querySelectorAll('[data-ds-frame]')].filter(visible).filter((el) => !insideInstance(el)).map((el) => {
    const f = JSON.parse(el.dataset.dsFrame)
    const bg = getComputedStyle(el).backgroundColor
    // A column only grey from 1024px (SplitView) is transparent below it: skip.
    if (bg === 'rgba(0, 0, 0, 0)' || bg === 'transparent') return null
    return { ...f, box: boxOf(el) }
  }).filter(Boolean)
  const instances = [...document.querySelectorAll('[data-ds]')].filter(visible).filter((el) => {
    const m = JSON.parse(el.dataset.ds)
    return m.overlay || !insideInstance(el)
  }).map((el) => {
    const m = JSON.parse(el.dataset.ds)
    const box = boxOf(el)
    // A pin is a turned square: place by its visible box.
    return { ...m, box }
  })
  const texts = [...document.querySelectorAll('[data-ds-text]')].filter(visible).filter((el) => !el.closest('[data-ds]')).map((el) => {
    const t = JSON.parse(el.dataset.dsText)
    const cs = getComputedStyle(el)
    return { ...t, chars: el.innerText.trim(), align: cs.textAlign === 'center' ? 'CENTER' : 'LEFT', box: boxOf(el) }
  }).filter((t) => t.chars)
  const targets = notes.map((n) => { const el = [...document.querySelectorAll(n.target)].find(visible); return el ? { n: n.n, box: boxOf(el) } : { n: n.n, missing: true } })
  const linkBoxes = links.map((l) => { const el = [...document.querySelectorAll(l.target)].find(visible); return el ? { to: l.to, back: !!l.back, box: boxOf(el) } : { to: l.to, missing: l.target } })
  return { frames, instances, texts, targets, linkBoxes }
}

const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width, height } })
await page.goto(`http://localhost:6007/iframe.html?id=${screen.story}&viewMode=story`)
await page.waitForSelector('[data-ds]')
await page.waitForTimeout(2500) // late renders (React Aria collections) and fonts
const data = await page.evaluate(read, { notes: screen.notes, links: screen.links ?? [], width, height })
await browser.close()

const lost = data.linkBoxes.filter((l) => l.missing)
if (lost.length) throw new Error(`links without a target on the page: ${lost.map((l) => l.missing).join(', ')}`)
const missing = data.targets.filter((t) => t.missing)
if (missing.length) throw new Error(`notes without a target on the page: ${missing.map((t) => t.n).join(', ')}`)
const spec = {
  $description: `Generated by scripts/figma/screen-spec.mjs from the story ${screen.story} at ${width} x ${height}. Do not edit: re-run it.`,
  id: screen.id, name: screen.name, page: screen.page, intro: screen.intro, viewport: screen.viewport,
  at: screen.at ?? { x: 0, y: 200 }, title: !!screen.title, caption: screen.caption,
  links: await Promise.all(data.linkBoxes.map(async (l) => (l.back ? { box: l.box, back: true } : { box: l.box, to: (await import(`./screens/${l.to}.mjs`)).screen.name }))),
  notes: screen.notes.map(({ target, ...n }) => ({ ...n, box: data.targets.find((t) => t.n === n.n).box })),
  frames: data.frames, instances: data.instances, texts: data.texts,
}
await mkdir('figma/screens', { recursive: true })
await writeFile(`figma/screens/${id}.json`, JSON.stringify(spec, null, 1) + '\n')
const sets = {}
for (const i of spec.instances) sets[i.set] = (sets[i.set] ?? 0) + 1
console.log(`✔ figma/screens/${id}.json: ${spec.instances.length} instances (${Object.entries(sets).map(([k, v]) => `${k} ${v}`).join(', ')}), ${spec.frames.length} backgrounds, ${spec.texts.length} texts, ${spec.notes.length} notes`)
