// Builds the DTCG token JSON in tokens/ into one CSS file, src/tokens.css.
//   :root               primitives + light semantic + component tokens
//   [data-theme="dark"] dark semantic tokens only, IF tokens/semantic-dark.json exists
// v1 is light only (docs/GOVERNANCE.md, decision 2). The dark run is kept so that
// adding a dark theme later means adding one JSON file, not changing this script.
// Component tokens are printed once: they point at semantic variables, so they
// follow the theme automatically.
// Run with: npm run tokens
import { existsSync } from 'node:fs'
import { writeFile } from 'node:fs/promises'
import StyleDictionary from 'style-dictionary'

const OUTPUT = 'src/tokens.css'
const LIGHT = 'tokens/semantic-light.json'
const DARK = 'tokens/semantic-dark.json'

// One theme = one Style Dictionary run. The light and dark files define the
// same names, so they must never be read in the same run or they'd collide.
async function buildTheme({ semantic, selector, includePrimitives }) {
  const sd = new StyleDictionary({
    source: ['tokens/primitives.json', semantic, 'tokens/components/*.json'],
    platforms: {
      css: {
        transformGroup: 'css',
        files: [
          {
            destination: OUTPUT,
            format: 'css/variables',
            // Primitives are always loaded so {color.brand.700} can resolve,
            // but the dark block only needs to print the semantic overrides.
            filter: includePrimitives
              ? undefined
              : (token) => token.filePath === semantic,
            options: {
              selector,
              // Print var(--color-brand-700) instead of the hex, so the CSS
              // shows the same tier structure as the JSON.
              outputReferences: true,
              showFileHeader: false,
            },
          },
        ],
      },
    },
    log: { verbosity: 'silent' },
  })
  const [file] = await sd.formatPlatform('css')
  return file.output
}

const parts = [
  await buildTheme({ semantic: LIGHT, selector: ':root', includePrimitives: true }),
]
if (existsSync(DARK)) {
  parts.push(
    await buildTheme({ semantic: DARK, selector: '[data-theme="dark"]', includePrimitives: false }),
  )
}

const header =
  '/**\n * Generated by scripts/build-tokens.mjs from tokens/*.json.\n * Do not edit by hand: change the JSON and run `npm run tokens`.\n */\n\n'
await writeFile(OUTPUT, header + parts.join('\n'))
console.log(`✔ ${OUTPUT}`)
